from typing import Protocol

from ..core.validation import ValidationRules


class UserProfileService(Protocol):
    def get(self, user_id: int) -> dict: ...
    def language(self, user_id: int, value: str) -> dict: ...
    def timezone(self, user_id: int, value: str) -> dict: ...


class CatalogService(Protocol):
    def search(self, query: str, os: str, platform: str | None = None) -> list[dict]: ...
    def get(self, game_id: str) -> dict: ...


class DeviceService(Protocol):
    def list(self, user_id: int) -> list[dict]: ...
    def get(self, user_id: int, device_id: str) -> dict: ...
    def add(self, user_id: int, os: str, name: str, primary_id: str, idfv: str | None, proxy_id: str | None = None) -> dict: ...
    def update_ids(self, user_id: int, device_id: str, ids: dict[str, str]) -> dict: ...
    def proxy(self, user_id: int, device_id: str, proxy_id: str | None) -> dict: ...
    def delete(self, user_id: int, device_id: str) -> None: ...
    def linked(self, user_id: int, device_id: str) -> list[dict]: ...
    def get_linked(self, user_id: int, linked_id: str) -> dict: ...
    def link_game(self, user_id: int, device_id: str, game_id: str, extra_id: str | None = None, expected_platform: str | None = None) -> dict: ...
    def edit_linked_id(self, user_id: int, linked_id: str, value: str) -> dict: ...
    def delete_linked(self, user_id: int, linked_id: str) -> None: ...


class ProxyService(Protocol):
    def list(self, user_id: int) -> list[dict]: ...
    def get(self, user_id: int, proxy_id: str) -> dict: ...
    def add(self, user_id: int, data: dict) -> dict: ...
    def edit(self, user_id: int, proxy_id: str, data: dict) -> dict: ...
    def delete(self, user_id: int, proxy_id: str) -> None: ...
    def dev_check(self, user_id: int, proxy_id: str, outcome: str) -> dict: ...


class EventPreviewService(Protocol):
    def preview(self, user_id: int, linked_id: str, template: str, values: list[str], kind: str) -> dict: ...


class ScheduledPlanService(Protocol):
    def list(self, user_id: int) -> list[dict]: ...
    def get(self, user_id: int, plan_id: str) -> dict: ...
    def add(self, user_id: int, device_id: str, linked_id: str, mode: str, shared: str | None, operations: list[dict]) -> dict: ...
    def edit_pending(self, user_id: int, plan_id: str, operations: list[dict], shared: str | None = None) -> dict: ...
    def delete(self, user_id: int, plan_id: str) -> None: ...
    def dev_fail_first(self, user_id: int, plan_id: str) -> dict: ...


class SubscriptionService(Protocol):
    def status(self, user_id: int) -> dict: ...
    def require_active(self, user_id: int) -> None: ...
    def require_quota(self, user_id: int) -> None: ...
    def dev_state(self, user_id: int, state: str) -> dict: ...
    def dev_expire(self, user_id: int, when) -> dict: ...
    def dev_advance(self, user_id: int, now) -> dict: ...
    def dev_renew(self, user_id: int, tier: str, now=None) -> dict: ...
    def dev_quota(self, user_id: int, exhausted: bool) -> dict: ...


class FinanceService(Protocol):
    def balance(self, user_id: int) -> float: ...
    def ledger(self, user_id: int) -> list[dict]: ...
    def dev_balance(self, user_id: int, amount: float) -> dict: ...


class ReferralService(Protocol):
    def stats(self, user_id: int) -> dict: ...
    def register(self, referrer_id: int, referred_id: int) -> bool: ...


class ServiceBundle(Protocol):
    validation_rules: ValidationRules
    users: UserProfileService
    catalog: CatalogService
    devices: DeviceService
    proxies: ProxyService
    events: EventPreviewService
    plans: ScheduledPlanService
    subscriptions: SubscriptionService
    finance: FinanceService
    referrals: ReferralService
    tiers: dict
